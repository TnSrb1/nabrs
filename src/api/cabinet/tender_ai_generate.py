async def precheck_generation(
    db: Any,
    *,
    tid: str,
    tender_id: str,
    profile_id: str,
    level: str,
    tier_limits: dict[str, dict[str, int | None]] | None = None,
) -> str:
    """A cheap synchronous precheck BEFORE the background task is queued.

    It goes through gate → cache → limit → existence of the tender / profile WITHOUT a model call, so that the route at once returns a clear partial (``gate_pro`` / ``frozen`` / ``already`` / ``limit_exhausted`` / ``no_tender`` / ``no_profile``) instead of starting a knowingly idle generation. ``STATUS_OK`` → the background task can be queued.
    """
    status, _ = await _prepare_generation(
        db,
        tid=tid,
        tender_id=tender_id,
        profile_id=profile_id,
        level=level,
        tier_limits=tier_limits,
    )
    return status


async def generate_artifact(
    db: Any,
    *,
    tid: str,
    tender_id: str,
    profile_id: str,
    level: str,
    ai_client: AiClient | None = None,
    tier_limits: dict[str, dict[str, int | None]] | None = None,
) -> str:
    """Generates the AI artifact of the level ``level`` for (tender, profile) under ``tid``.

    The full sequence on ``tid`` (WITHOUT chat_id): ``set_tenant`` → tier / access_until → frozen? → Pro+ gate → cache_lookup (present → ``already``, without a write-off) → limit_decision → loading of the tender / profile → ``AnalysisRequest`` + ``client.analyze`` → ``finalize_with_insert`` (INSERT + UPSERT of usage).

    ‼️ Called from ``BackgroundTasks`` with ITS OWN session (the route’s session is already closed) — therefore ``set_tenant`` inside ``_prepare_generation`` FIRST. Returns a status string (``STATUS_*``). The idempotency of the race between two parallel requests of one level is provided by UNIQUE(tender_id, profile_id, level) in ``tender_ai_analyses`` (softly resolved in ``finalize_with_insert``).
    """
    client = ai_client or _get_default_ai_client()

    # The race of two parallel /generate calls: both passed the precheck (the cache empty) and both
    # went to the background. We serialize with a xact advisory lock on (tid, tender, profile, level):
    # ``set_tenant`` FIRST (RLS), then a try-lock. The second parallel call does NOT take
    # the lock → ``in_progress`` (the route shows “generating…”, the polling picks up
    # the result of the first) — without a second AI call / write-off. The lock is held until the
    # commit / rollback of THIS transaction, so the whole expensive path runs under it, and
    # ``cache_lookup`` inside ``_prepare_generation`` serves as a REPEAT check
    # under the lock (the first one could have written while we were taking the lock) → ``already``.
    await repo.set_tenant(db, tid)
    if not await _try_generation_lock(
        db, tid=tid, tender_id=tender_id, profile_id=profile_id, level=level
    ):
        logger.info(
            "web-ai: a parallel generation is already running tender=%s profile=%s level=%s",
            tender_id,
            profile_id,
            level,
        )
        return STATUS_IN_PROGRESS

    status, ctx = await _prepare_generation(
        db,
        tid=tid,
        tender_id=tender_id,
        profile_id=profile_id,
        level=level,
        tier_limits=tier_limits,
    )
    if status != STATUS_OK or ctx is None:
        return status

    model_tier = _DRAFT_TIER_MODEL.get(ctx.tier or "") if level == "draft" else None
    request = AnalysisRequest(
        level=level,
        title=ctx.title,
        description=ctx.description,
        country_name=ctx.country_name,
        target_language=ctx.target_language,
        extra_context=ctx.profile_context,
        model_tier=model_tier,
    )

    # Step-wise mode (deep/checklist, decided by Scout): the generation advisory lock is released
    # by the commit of the step's write to ai_usage → after each step we take it again.
    async def _relock() -> None:
        # The lock was not taken — a parallel click is already running its own paid analysis: this one
        # is stopped (already paid steps are recorded), otherwise the analysis is paid twice.
        if not await _try_generation_lock(
            db, tid=tid, tender_id=tender_id, profile_id=profile_id, level=level
        ):
            raise _GenerationLockLost

    try:
        if level in STEPWISE_LEVELS:
            result = await analyze_tender(
                client,
                request,
                record_spend=step_recorder(
                    db, tenant_id=tid, level=level, after_commit=_relock
                ),
                documents=ctx.documents,
            )
        else:
            result = await client.analyze(request)
    except _GenerationLockLost:
        logger.info(
            "web-ai: lock taken by a parallel request tender=%s profile=%s level=%s",
            tender_id,
            profile_id,
            level,
        )
        return STATUS_IN_PROGRESS
    except AiRetryableError:
        logger.warning(
            "web-ai: model busy tender=%s profile=%s level=%s",
            tender_id,
            profile_id,
            level,
        )
        return STATUS_MODEL_BUSY
    except Exception as exc:  # noqa: BLE001 — any other model error is terminal
        logger.exception(
            "web-ai: analysis error tender=%s profile=%s level=%s",
            tender_id,
            profile_id,
            level,
        )
        await record_error_spend(db, tenant_id=tid, level=level, exc=exc)
        return STATUS_MODEL_ERROR

    analysis_id = await finalize_with_insert(
        db,
        tender_id=tender_id,
        profile_id=None if level in _TENDER_WIDE_LEVELS else profile_id,
        tenant_id=tid,
        level=level,
        result=result,
    )
    if analysis_id is None:
        logger.error(
            "web-ai: finalize returned None tender=%s level=%s", tender_id, level
        )
    logger.info(
        "web-ai: generated %s tender=%s profile=%s analysis=%s",
        level,
        tender_id,
        profile_id,
        analysis_id,
    )
    return STATUS_SUCCESS



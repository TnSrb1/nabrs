class _GenerationLockLost(Exception):
    """advisory lock of generation taken by another request in the middle of a step-wise analysis."""


async def _try_generation_lock(
    db: Any,
    *,
    tid: str,
    tender_id: str,
    profile_id: str,
    level: str,
) -> bool:
    """Tries to take the xact advisory lock on (tid, tender, profile, level).

    The key is a stable string ``f"{tid}:{tender_id}:{profile_id}:{level}"``, folded by ``hashtextextended`` into a bigint. For the levels of ``_TENDER_WIDE_LEVELS`` (deep: cache ``profile_id IS NULL``, shared per tender) the key is WITHOUT profile and tenant — otherwise two profiles or two tenants would pay twice for the same analysis. ``True`` — the lock is taken (we generate); ``False`` — held by another request (we return ``in_progress``). The lock is transactional: it is released on the commit / rollback of the calling transaction automatically.
    """
    if level in _TENDER_WIDE_LEVELS:
        key = f"{tender_id}:{level}"
    else:
        key = f"{tid}:{tender_id}:{profile_id}:{level}"
    row = (await db.execute(_TRY_GEN_LOCK_SQL, {"key": key})).first()
    return bool(row.locked) if row is not None else False


async def load_tenant_access(db: Any, tid: str) -> tuple[bool, str]:
    """The freeze axis + the tenant’s effective plan in ONE selection: ``(frozen, tier)``.

    The common brick for all paid gates of the cabinet (artifact generation here, the card translation — in ``routes_tender_ai``): the decision “call the model or not” must read the plan and the freeze with ONE query and in ONE order, otherwise two copies of the predicate would diverge.

    The order is from ``src/domain/tiers``: the freeze is checked FIRST and separately — a frozen trial does not get Pro rights. No tenant / empty fields → ``effective_tier`` gives the fallback ``lite`` (fail-closed on rights).

    ‼️ The caller must do ``set_tenant(tid)`` BEFORE (RLS).
    """
    row = (await db.execute(_LOAD_TENANT_TIER_SQL, {"tid": str(tid)})).first()
    access_until = getattr(row, "access_until", None) if row is not None else None
    frozen = is_frozen(access_until, datetime.now(timezone.utc))
    status_val = str(row.status) if row and getattr(row, "status", None) else None
    raw_tier = str(row.tier) if row and row.tier else None
    return frozen, effective_tier(status_val, raw_tier)


async def _prepare_generation(
    db: Any,
    *,
    tid: str,
    tender_id: str,
    profile_id: str,
    level: str,
    tier_limits: dict[str, dict[str, int | None]] | None,
) -> tuple[str, _GenContext | None]:
    """Gate → cache → limit → loading of the tender / profile. Returns (status, ctx|None).

    ``set_tenant(tid)`` FIRST (RLS, otherwise 0 rows fail-closed / UndefinedObjectError). ``(STATUS_OK, ctx)`` → everything is ready for the model call; otherwise ``(terminal STATUS_*, None)``.
    """
    limits = tier_limits if tier_limits is not None else _TIER_LIMITS
    if level not in GENERATABLE_LEVELS:
        return STATUS_NO_TENDER, None  # a defensive guard — the route already validates

    await repo.set_tenant(db, tid)

    # The plan, the freeze and the Pro+ gate. The effective plan: trial → Pro rights
    # (ARCHITECTURE §4), AFTER the frozen gate. It also feeds both the limit and the model choice.
    # draft (ctx.tier → _DRAFT_TIER_MODEL).
    frozen, tier = await load_tenant_access(db, tid)
    if frozen:
        return STATUS_FROZEN, None
    tier_row = limits.get(tier, {})
    if tier_row.get(level, 0) == 0:
        return STATUS_GATE_PRO, None

    # Cache (profile_id is mandatory — the artifact depends on the profile). Present → already.
    tender_wide = level in _TENDER_WIDE_LEVELS
    cached_id = await cache_lookup(
        db, tender_id, None if tender_wide else profile_id, level
    )
    if cached_id is not None:
        return STATUS_ALREADY, None

    # The monthly limit of the level §14.5.
    decision = await limit_decision(
        db, tenant_id=tid, tier=tier, level=level, tier_limits=limits
    )
    if decision == "exhausted":
        return STATUS_LIMIT_EXHAUSTED, None
    if decision != "ok":
        return STATUS_GATE_PRO, None

    # Loading the tender.
    tender_row = (
        await db.execute(_LOAD_TENDER_SQL, {"tender_id": tender_id, "tid": str(tid)})
    ).first()
    if tender_row is None:
        return STATUS_NO_TENDER, None

    # Loading the profile with a tenant-ownership check (someone else’s → no_profile).
    profile_row = (
        await db.execute(_LOAD_PROFILE_SQL, {"profile_id": profile_id, "tid": str(tid)})
    ).first()
    if profile_row is None:
        return STATUS_NO_PROFILE, None

    if tender_wide:
        # As in the bot (deep_analysis_service): without a profile and a track record, language ru.
        return STATUS_OK, _GenContext(
            tier=tier,
            title=str(tender_row.title) if tender_row.title else "",
            description=str(tender_row.description) if tender_row.description else "",
            country_name=(
                str(tender_row.country_name) if tender_row.country_name else "Сербия"
            ),
            target_language="ru",
            profile_context="",
            documents=getattr(tender_row, "documents", None),
        )

    # The track record under the same tenant GUC (set_tenant(tid) was called FIRST above) —
    # the company’s behavioral memory goes into the same profile_context.
    track_record = await build_track_record_context(db, tid)
    ctx = _GenContext(
        tier=tier,
        title=str(tender_row.title) if tender_row.title else "",
        description=str(tender_row.description) if tender_row.description else "",
        country_name=(
            str(tender_row.country_name) if tender_row.country_name else "Сербия"
        ),
        target_language=(
            str(profile_row.target_language) if profile_row.target_language else "ru"
        ),
        profile_context=format_profile_context(
            classifications=getattr(profile_row, "classifications", None),
            regions=getattr(profile_row, "regions", None),
            keywords_include=getattr(profile_row, "keywords_include", None),
            min_amount_eur=getattr(profile_row, "min_amount_eur", None),
            max_amount_eur=getattr(profile_row, "max_amount_eur", None),
            procedure_types=getattr(profile_row, "procedure_types", None),
            ai_extra_context=getattr(profile_row, "ai_extra_context", None),
            track_record=track_record,
        ),
        documents=getattr(tender_row, "documents", None),
    )
    return STATUS_OK, ctx

logger = logging.getLogger(__name__)

# The levels the user may generate from the web cabinet. bid / checklist / draft
# are profile-specific (cache per (tender_id, profile_id)); deep — COMMON per tender
# (profile_id NULL), like the bot’s button. standard / quick generate the auto pipeline
# and the web buttons do not have them.
GENERATABLE_LEVELS: tuple[str, ...] = ("bid", "checklist", "draft", "deep")

# Levels without a profile link: cache / INSERT with profile_id=NULL, the profile is not mixed
# into the prompt (a mirror of ``bots.deep_analysis_service.run_deep_analysis``).
_TENDER_WIDE_LEVELS: frozenset[str] = frozenset({"deep"})

# The status outcome of the generation / precheck (enum strings for the route and the tests).
STATUS_OK = "ok"  # the precheck passed — the background task can be started
STATUS_SUCCESS = "success"  # the artifact is generated and saved
STATUS_ALREADY = "already"  # already in the cache (no new call, no write-off)
STATUS_GATE_PRO = "gate_pro"  # the level is unavailable on the plan (Pro+ gate)
STATUS_LIMIT_EXHAUSTED = "limit_exhausted"  # the level’s monthly limit is exhausted
STATUS_FROZEN = "frozen"  # access is frozen (access_until has expired)
STATUS_NO_TENDER = "no_tender"  # tender not found
STATUS_NO_PROFILE = "no_profile"  # profile does not belong to the tenant / is deleted
STATUS_MODEL_BUSY = "model_busy"  # the model is temporarily busy (retries exhausted)
STATUS_MODEL_ERROR = "model_error"  # error / invalid model response
STATUS_IN_PROGRESS = "in_progress"  # the same (tid, tender, profile, level) is already being generated by
# another request (advisory lock taken) — without a second call / write-off; the polling waits

# The mapping of plan → model plan for draft (VG-10; mirrors draft_service, the bot is NOT touched).
_DRAFT_TIER_MODEL: dict[str, str] = {
    "pro": "balanced",
    "business": "premium",
    "enterprise": "premium",
}

# A transactional advisory lock serializing the generation of one
# (tid, tender, profile, level): xact-scope (it is released by the commit / rollback of the same
# transaction). ``hashtextextended(text, 0)`` → bigint key; the try variant does NOT
# wait (zero contention does not block polling). asyncpg → CAST(:key AS text).
_TRY_GEN_LOCK_SQL = text("""
    SELECT pg_try_advisory_xact_lock(hashtextextended(CAST(:key AS text), 0)) AS locked
    """)

_LOAD_TENANT_TIER_SQL = text("""
    SELECT tier, access_until, status FROM tenants WHERE id = CAST(:tid AS uuid)
    """)

# The tender + the tenant’s country (as in the bot services, but tenant_id = tid from the web session).
_LOAD_TENDER_SQL = text("""
    SELECT tn.title, tn.description, tn.documents, c.name AS country_name
    FROM tenders_normalized tn
    JOIN tenants t ON t.id = CAST(:tid AS uuid)
    LEFT JOIN countries c ON c.code = t.country_code
    WHERE tn.id = CAST(:tender_id AS uuid)
    LIMIT 1
    """)

# The profile by id WITH AN EXPLICIT check of tenant ownership (defense-in-depth to RLS).
_LOAD_PROFILE_SQL = text("""
    SELECT
        p.classifications  AS classifications,
        p.regions          AS regions,
        p.keywords_include AS keywords_include,
        p.min_amount_eur   AS min_amount_eur,
        p.max_amount_eur   AS max_amount_eur,
        p.procedure_types  AS procedure_types,
        p.ai_extra_context AS ai_extra_context,
        p.target_language  AS target_language
    FROM profiles p
    WHERE p.id = CAST(:profile_id AS uuid)
      AND p.tenant_id = CAST(:tid AS uuid)
      AND p.deleted_at IS NULL
    LIMIT 1
    """)


@dataclass(frozen=True)
class _GenContext:
    """The assembled context of the model request (after a successful precheck)."""

    tier: str | None
    title: str
    description: str
    country_name: str
    target_language: str
    profile_context: str
    documents: Any = None  # file list (tn.documents) — for Scout


_DEFAULT_AI_CLIENT: AiClient | None = None


def _get_default_ai_client() -> AiClient:
    global _DEFAULT_AI_CLIENT
    if _DEFAULT_AI_CLIENT is None:
        _DEFAULT_AI_CLIENT = AiClient()
    return _DEFAULT_AI_CLIENT



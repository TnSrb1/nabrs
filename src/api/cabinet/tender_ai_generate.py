"""Web generation of AI artifacts from the cabinet (web-ai-2, step 2).

“Value up to the web” STEP 2: we let the user START the generation of the bid verdict / checklist / draft right from the cabinet (step 1 web-ai-1 — only a read-only view of what is already generated). An AI call of 10–60 s → the route puts this function into ``BackgroundTasks`` with ITS OWN session, and the front end polls the read view (:mod:`src.api.cabinet.tender_ai_service`) via HTMX polling.

The sequence is assembled from the SHARED primitives of :mod:`src.ai.usage` (``cache_lookup`` / ``limit_decision`` / ``finalize_with_insert``) and :class:`src.ai.AiClient` — the sample gate → cache → limit → analyze → finalize is taken from :func:`src.bots.bid_verdict_service.run_bid_verdict` (the bot files are NOT edited, only read as a sample). Differences from the bot:

- ``tid`` is taken from the web session (NOT ``chat_id`` → there is no ``resolve_tenant_id``);
- ``profile_id`` comes as an explicit query parameter and is checked for belonging to the tenant (``WHERE tenant_id`` + FORCE RLS 0003);
- there is no rendering into Telegram HTML — the artifact goes into ``tender_ai_analyses``, and the web shows it through the read view.

The gating axis is NOT duplicated: the thresholds are only through ``limit_decision`` and ``_TIER_LIMITS`` (usage.py). ``set_tenant(tid)`` is the FIRST action of EVERY transaction, including the background task (which has ITS OWN session).
"""


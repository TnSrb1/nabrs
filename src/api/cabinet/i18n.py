"""Multilingual cabinet — sr/ru/en. Phase 1.1: framework + switcher.

The model — :mod:`src.api.public.i18n` (the showcase is already multilingual). Here is a SEPARATE
resolver for the authed contour: the saved user choice (``users.locale``)
takes priority over a random cookie ``lang`` left by the public site.

The priority of the language choice (``resolve_authed_lang``):
    ?lang=<code>  →  ``users.locale``  →  cookie ``lang``  →  ``sr``
    (the default of the cabinet; ``Accept-Language`` is NOT taken into account — owner’s decision 30.09.2026).

‼️ ``users.locale`` is ABOVE the cookie: the explicit choice in the cabinet header must not be overridden by
a random cookie that came from the public showcase.

The two axes of language are not to be mixed (the project rules): the INTERFACE language (``users.locale``, this
module) ≠ the language of the AI CONTENT (``profiles.target_language``). Only the chrome here.

Catalogs:
    CABINET — the chrome of the frame (header/navigation/footer/switcher).
    COMMON  — the common vocabulary bot↔cabinet: the funnel statuses (``tender_user_status``) and
              the plan names. We keep them in ONE place, so that the bot and the cabinet do not diverge.

``cabinet_context(request, user_locale)`` returns ``{"t", "lang", "lang_names"}``,
where ``t`` is a flat dict of strings (``COMMON`` ∪ ``CABINET`` for the chosen language).
The ``Accept-Language`` parser is reused from the public module (not copied).
"""

from __future__ import annotations

from typing import TypedDict

from starlette.requests import Request

# The common Accept-Language parser — the public SUPPORTED matches the cabinet one
# (sr/ru/en), therefore we reuse it without copying (see TASK: do not duplicate).

# The common vocabulary bot↔cabinet (funnel statuses, plan names) lives in a NEUTRAL
# module: the bot imports it too, and the bot cannot pull starlette through
# src.api.cabinet. We keep one catalog, so that the bot and the cabinet do not diverge (the project rules).
from src.i18n_common import COMMON

SUPPORTED: tuple[str, ...] = ("sr", "ru", "en")
DEFAULT = (
    "sr"  # the cabinet default = the market language (owner’s decision 30.09.2026)
)
LANG_COOKIE = "lang"

# Language switcher labels (display codes) — the same as on the showcase.
LANG_NAMES: dict[str, str] = {"sr": "SR", "ru": "RU", "en": "EN"}


def resolve_authed_lang(
    request: Request, user_locale: str | None, *, include_query: bool = True
) -> str:
    """Cabinet interface language: ?lang= → users.locale → cookie → sr (Accept-Language is ignored).

    ``user_locale`` — the saved ``users.locale`` of the current user (or
    ``None`` for an anonymous visitor / an unfilled field). It takes priority over the cookie: an explicit
    choice is stronger than a random cookie from the public site.

    ‼️ ``include_query=False`` — do NOT read ``?lang=`` from the request. It is needed where the
    query parameter ``lang`` is taken by ANOTHER axis (the translation of the tender’s CONTENT:
    ``sr``=original / ``ru``=machine translation, htmx fragments ``/title`` and
    ``/description``). The two axes must not be mixed (the project rules): the chrome of a fragment
    must follow the user’s INTERFACE language, not the translation toggle.
    """
    if include_query:
        chosen = request.query_params.get("lang")
        if chosen in SUPPORTED:
            return chosen
    if user_locale in SUPPORTED:
        return user_locale
    cookie = request.cookies.get(LANG_COOKIE)
    if cookie in SUPPORTED:
        return cookie
    return DEFAULT



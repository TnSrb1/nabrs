def _slavic_plural_index(n: int) -> int:
    """Plural-form index one/few/many for ru/sr by number (standard CLDR rule).

    11–14 → “many” (an exception to the last-digit rule); otherwise by the last digit: 1 → one, 2–4 → few, the rest → many. The rule is the same for ru and sr (sr “other” = ru “many”).
    """
    if 11 <= n % 100 <= 14:
        return 2
    if n % 10 == 1:
        return 0
    if 2 <= n % 10 <= 4:
        return 1
    return 2


def plural(lang: str, key: str, n: int) -> str:
    """Noun form for ``key`` at number ``n`` in language ``lang``.

    The form-selection rule is PER LOCALE (ru/sr: Slavic three-form, en: two-form); the forms come from the catalog :data:`PLURALS`. Forms with ``{n}`` get the number; forms without ``{n}`` are returned as is (the number is already rendered next to them). Unknown language → the cabinet default (:data:`DEFAULT`).
    """
    lang = lang if lang in PLURALS else DEFAULT
    forms = PLURALS[lang][key]
    n = abs(int(n))
    idx = (0 if n == 1 else 1) if lang == "en" else _slavic_plural_index(n)
    return forms[idx].format(n=n)


class CabinetContext(TypedDict):
    """Cabinet chrome context: flat string catalog, language and language-switcher labels."""

    t: dict[str, str]
    lang: str
    lang_names: dict[str, str]


def cabinet_context(
    request: Request, user_locale: str | None, *, include_query: bool = True
) -> CabinetContext:
    """Base i18n context of the cabinet: ``t`` (COMMON ∪ CABINET), language, switcher.

    ``include_query`` is passed to :func:`resolve_authed_lang`: ``False`` — ignore ``?lang=`` (the query is taken by the content-translation axis, see its docstring).
    """
    lang = resolve_authed_lang(request, user_locale, include_query=include_query)
    return cabinet_context_for_lang(lang)


def cabinet_context_for_lang(lang: str) -> CabinetContext:
    """The same context, but for an ALREADY resolved language (resolver outside).

    Needed by anonymous login screens: there the language is set by the SHOWCASE contour (:func:`src.api.public.i18n.resolve_lang`, default ``sr``), while the string catalog stays the cabinet one. One assembly point for ``t``, so the catalog composition (``COMMON`` ∪ ``CABINET``) does not diverge between the two paths.
    """
    return {
        "t": {**COMMON[lang], **CABINET[lang]},
        "lang": lang,
        "lang_names": LANG_NAMES,
    }

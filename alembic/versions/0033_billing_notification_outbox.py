"""billing_notification_outbox + SECURITY DEFINER enqueue/pending/mark (blocker #3)

Queue of payment lifecycle emails. The webhook silently changed the DB (payment went through /
failed / canceled / renewed) — the subscriber did not know the status of their money
(LAUNCH_AUDIT §3). The core ``apply_billing_event`` now puts a row into this
queue IN THE SAME TRANSACTION as the webhook's dedup-claim, and the standalone worker
``src.workers.billing_notifications`` processes it and sends the email.

Scope (STRICTLY per CLAUDE.md — fail-closed, model ``admin_audit_log`` 0030):

* ``billing_notification_outbox`` — a platform table (NOT tenant-scoped: the idempotency key is
  the webhook's ``(provider, event_id)``, as in ``billing_webhook_events``), so there is no RLS
  on it. But 0021 granted ``ALTER DEFAULT PRIVILEGES ... GRANT SELECT/INSERT/UPDATE/DELETE ON TABLES``
  to the ``tendersrb_app`` role — so the new table would automatically get direct access.
  That breaks “direct app-role access is fail-closed”, so here we EXPLICITLY
  revoke all privileges from ``tendersrb_app`` on the table and its identity sequence.
  The role writes/reads the queue ONLY through the SECURITY DEFINER functions below
  (owner — superuser ``tendersrb``, bypasses the table grant control).
* ``app_billing_enqueue_notification`` — idempotent enqueue (ON CONFLICT
  ``(provider, event_id)`` DO NOTHING): a double webhook = one email. Called by
  the core in one transaction with the dedup claim.
* ``app_billing_pending_notifications`` — not-yet-sent rows with the already-resolved
  email + access_until + tenant tz (the addressee = the oldest user with a
  valid email; the ORDER BY branch mirrors ``channel_dead_notify`` 0031).
* ``app_billing_mark_notification_sent`` — atomic claim of a row
  (``UPDATE ... WHERE sent_at IS NULL RETURNING id``): a double run of the worker =
  one email.

All three — pattern 1:1 with ``app_admin_*`` (0025/0030) and ``app_billing_*`` (0028):
``SECURITY DEFINER``, ``SET search_path = public``, ``GRANT EXECUTE ...
TO tendersrb_app``.

Revision ID: 0033
Revises: 0032
Create Date: 2026-07-17
"""

